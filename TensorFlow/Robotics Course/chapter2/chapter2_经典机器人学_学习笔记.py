import numpy as np


def fk_2link(theta1, theta2, l1=1.0, l2=1.0):
    """二连杆平面臂正运动学:关节角(弧度) → 末端 (x,y)。"""
    x = l1 * np.cos(theta1) + l2 * np.cos(theta1 + theta2)
    y = l1 * np.sin(theta1) + l2 * np.sin(theta1 + theta2)
    return np.array([x, y])


def main():
    p0 = fk_2link(0.0, 0.0)                      # 两杆伸直朝 x → (2,0)
    p1 = fk_2link(np.pi / 2, 0.0)               # 第一杆朝上 → (0,2)
    p2 = fk_2link(np.pi / 2, -np.pi / 2)        # 肘部回折 → (1,1)
    assert np.allclose(p0, [2, 0]) and np.allclose(p1, [0, 2], atol=1e-9)
    assert np.allclose(p2, [1, 1], atol=1e-9)
    print(f"✅ Ch2 跑通：FK (0,0)→{p0.round(2)} · (90°,0)→{p1.round(2)} · (90°,-90°)→{p2.round(2)}")

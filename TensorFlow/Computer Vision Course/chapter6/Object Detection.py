# 分类与定位
# 分类根据物体的独特属性区分物体，而定位则确定物体在图像中的位置。目标检测结合了这两种方法，既能定位物体，又能为其分配相应的类别标签。想象一下，识别不同种类的水果，并精确定位它们在单张图像中的位置。这就是目标检测的应用！
from transformers import pipeline
from PIL import Image

pipe = pipeline("object-detection", model="facebook/detr-resnet-50")

image = Image.open("path/to/your/image.jpg").convert("RGB")

bounding_boxes = pipe(image)
# 指标包括：
#
# 交并比 (IoU) 或 Jaccard 指数衡量预测标签与参考标签之间的重叠程度，以 0% 到 100% 的百分比表示。IoU 百分比越高，表示匹配度越好，即准确率越高。该指标在评估追踪器在不断变化的环境下的性能时非常有用，例如，在野生动物迁徙过程中进行追踪。
#
# 平均精度均值 (mAP)通过精确率（正确预测率）和召回率（真正例识别率）来评估目标检测效率。mAP 可在不同的 IoU 阈值下计算，作为目标检测算法的综合评估工具。它有助于确定模型在复杂条件下（例如在制造零件中寻找大小和形状各异的不规则表面缺陷）的定位和检测性能。
#
# 图像分割
# 图像分割是将图像分割成有意义的区域。其核心在于创建能够突出显示图像中每个对象的掩码。这项任务的直观理解是，它可以被视为对图像中每个像素进行分类。分割模型是各行各业的核心模型，例如农业和自动驾驶领域。在农业领域，这些模型用于识别不同的土地区域并评估作物的生长阶段。它们也是自动驾驶汽车的关键组成部分，用于识别车道、人行道和其他道路使用者。
#
# 图像分割
#
# 根据具体情况和预期目标，可以应用不同类型的细分方法。以下是一些最常用的细分方法。
#
# 语义分割：这涉及到为每个像素分配最可能的类别。例如，在语义分割中，模型并不区分两只不同的猫，而是关注像素的类别。其核心在于对每个像素进行分类。
# 实例分割：这种类型涉及使用唯一的掩码来识别对象的每个实例。它结合了对象检测和分割的各个方面，以区分同一类别的不同对象。
# 全景分割：一种结合语义分割和实例分割元素的混合方法。它为每个像素分配一个类别和一个实例，有效地整合了图像的“是什么”和“在哪里”两个方面。
# 分割类型比较
#
# 选择合适的分割类型取决于具体情况和预期目标。值得一提的是，最新的模型能够使用单个模型实现三种分割类型。我们推荐您阅读这篇文章，其中介绍了 Meta 开发的新模型 Mask2former，该模型仅使用 Panoptic 数据集即可实现三种分割类型。
#
# 现代方法：基于视觉变换器的分割
# 你可能听说过 U-Net，这是一种用于图像分割的流行网络。它由多个卷积层组成，主要分两个阶段进行：下采样阶段，压缩图像以了解其特征；以及上采样阶段，将图像恢复到原始大小以进行更精细的分割。
#
# 计算机视觉领域曾经以卷积模型为主导，但近年来已逐渐转向视觉变换器（Vision Transformer）方法。例如，Meta AI Research于 2023 年 4 月推出了一款名为“分割任意对象模型”（Segment Anything Model，简称 SAM）的热门提示式分割模型。该模型基于视觉变换器（ViT）模型，专注于创建一个可提示的（即用户可以通过提供词语来描述图像中想要分割的内容）分割模型，并能够在新图像上实现零样本迁移。该模型的优势在于其训练使用了目前最大的数据集，该数据集包含超过 10 亿个掩码，分布在 1100 万张图像上。我建议您使用Meta 提供的演示程序在几张图像上进行体验，或者更好的是，您也可以在 Transformer 环境中尝试使用该模型。

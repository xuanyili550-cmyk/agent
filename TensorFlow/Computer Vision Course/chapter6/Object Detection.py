# 如何评估细分模型？
# 您现在已经了解了如何使用分割模型，但如何评估它呢？如上一节所示，分割主要是一个监督学习任务。这意味着数据集由图像及其对应的掩码组成，掩码作为真实标签。可以使用一些指标来评估您的模型。最常用的指标包括：
#
# 交并比 (IoU) 或 Jaccard 指数是预测掩码与真实掩码的交集与并集的比值。IoU 可以说是分割任务中最常用的指标。​​它的优势在于对类别不平衡不太敏感，因此在建模初期通常是不错的选择。
# 借记卡
#
# 像素准确率：像素准确率的计算方法是正确分类的像素数与总像素数的比值。虽然这是一个直观的指标，但由于其对类别不平衡的敏感性，可能会产生误导。
# 像素精度
#
# Dice系数：它是预测掩码与真实值交集的两倍与预测掩码和真实值之和的比值。Dice系数简单来说就是预测结果与真实值重叠的百分比。当需要对重叠部分之间的细微差异保持敏感时，它是一个很好的指标。


#音频变压器架构
# 变压器的工作原理是什么？
# 最初的Transformer模型设计用于将一种语言的文本翻译成另一种语言。
# 左边是编码器，右边是解码器。
#
# 编码器接收输入（在本例中为文本标记序列），并构建其表示（即特征）。模型的这一部分经过训练，能够理解输入内容。
#
# 解码器利用编码器的表示（特征）以及其他输入（先前预测的词元）生成目标序列。
# 模型的这一部分经过训练，可以生成输出。在最初的设计中，输出序列由文本词元组成。
#
# 还有一些基于Transformer的模型，它们只使用编码器部分（适用于需要理解输入的任务，例如分类），
# 或者只使用解码器部分（适用于文本生成等任务）。BERT就是一个只使用编码器的模型的例子；
# GPT2就是一个只使用解码器的模型的例子。
#
# Transformer模型的一个关键特征是它们由称为注意力层的特殊层构成。这些层指示模型在计算特征表示时，
# 特别关注输入序列中的某些元素，而忽略其他元素。
#
# 对于音频任务，输入和/或输出序列可能是音频而不是文本：
#
# 自动语音识别（ASR）：输入为语音，输出为文本。
#
# 语音合成（TTS）：输入为文本，输出为语音。
#
# 音频分类：输入是音频，输出是类别概率——序列中的每个元素一个概率，或者整个序列一个类别概率。
#
# 语音转换或语音增强：输入和输出均为音频。
#
# 有几种不同的方法可以处理音频，使其能够与转换器一起使用。主要考虑因素是使用音频的原始形式（波形），还是将其处理成频谱图。

#CTC架构
# 连接主义时间分类（CTC）是一种用于自动语音识别的技术，它通常与仅包含编码器的Transformer模型一起使用。
# Wav2Vec2 、HuBERT和M-CTC-T就是这类模型的例子。
#
# 仅编码器Transformer是最简单的Transformer类型，因为它只使用模型中的编码器部分。
# 编码器读取输入序列（音频波形），并将其映射到一系列隐藏状态，也称为输出嵌入。
#
# 使用CTC模型，我们对隐藏状态序列应用额外的线性映射，以获得类别标签预测。
# 类别标签是字母表中的字符（a、b、c、…）。这样，我们只需一个较小的分类头即可预测目标语言中的任何单词，
# 因为词汇表只需要包含26个字符以及一些特殊标记。
# CTC算法

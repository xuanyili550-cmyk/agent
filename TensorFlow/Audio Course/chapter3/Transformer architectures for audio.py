# Wav2Vec2、HuBERT、M-CTC-T……之间有什么区别？
# 所有基于变压器的CTC模型都具有非常相似的架构：它们都使用变压器编码器（但不使用解码器），
# 并在其上安装CTC磁头。从架构上看，它们的相似之处远大于差异。
#
# Wav2Vec2 和 M-CTC-T 的一个区别在于，前者处理原始音频波形，而后者使用梅尔频谱图作为输入。
# 这两个模型的训练目的也不同。例如，M-CTC-T 是为多语言语音识别而训练的，因此其 CTC 词头相对较大，
# 除了其他字母外，还包含汉字。
#
# Wav2Vec2 和 HuBERT 使用完全相同的架构，但训练方式截然不同。Wav2Vec2 的预训练方式类似于
# BERT 的掩码语言模型，通过预测音频中被掩码部分的语音单元来进行训练。HuBERT 在此基础上更进一步，
# 学习预测“离散语音单元”，这些单元类似于文本句子中的词元，因此可以使用现有的自然语言处理技术来处理语音。


#Seq2Seq架构
# 编码器的输出随后通过一种称为交叉注意力机制的机制传递给右侧所示的Transformer解码器。
# 这类似于自注意力机制，但它关注的是编码器的输出。从这一点开始，就不再需要编码器了。
#
# 解码器以自回归的方式预测文本标记序列，每次预测一个标记，初始序列仅包含一个
# “开始”标记（SOT以 Whisper 为例）。在每个后续时间步，前一个时间步的输出序列都会作为新的输入序列反馈到解码器中。
# 如此循环往复，解码器每次输出一个新标记，不断增长输出序列，直到预测到“结束”标记或达到最大时间步数为止。
#
# 虽然解码器的架构与编码器的架构基本相同，但两者之间存在两个主要区别：
#
# 解码器具有交叉注意力机制，使其能够查看编码器对输入序列的表示。
# 解码器的注意力是因果性的——解码器不允许窥探未来。
# 在这种设计中，解码器扮演着语言模型的角色，处理来自编码器的隐藏状态表示并生成相应的文本转录。
# 即使将 CTC 模型与外部语言模型结合使用，这种方法也比 CTC 更强大，
# 因为 seq2seq 系统可以使用相同的训练数据和损失函数进行端到端训练，从而提供更大的灵活性和更优的性能。
# 对于序列到序列自动语音识别（seq2seq ASR）模型，典型的损失函数是交叉熵损失，
# 因为模型的最后一层预测的是所有可能词元的概率分布。这通常会结合束搜索等技术来生成最终序列。
# 语音识别的评价指标是词错误率（WER），它衡量的是将预测文本转换为目标文本所需的替换、
# 插入和删除次数——次数越少，得分越高。
#音频分类架构
# 利用频谱图进行分类
# 进行音频分类最简单的方法之一就是把它当作图像分类问题来处理！
#
# 回想一下，频谱图是一个二维张量，形状为(frequencies, sequence length)。在音频数据章节中，
# 我们将这些频谱图绘制成了图像。猜猜看？我们可以直接将频谱图当作图像来处理，
# 并将其输入到诸如 ResNet 之类的常规 CNN 分类器模型中，从而获得非常好的预测结果。
# 更棒的是，我们还可以使用诸如 ViT 之类的图像转换器模型。
#
# 这就是音频频谱图转换器（Audio Spectrogram Transformer）的工作原理。
# 它使用视觉转换器（ViT）模型，并将频谱图而非普通图像作为输入。由于转换器具有自注意力层，
# 因此该模型比卷积神经网络（CNN）更能捕捉全局上下文信息。
#
# 与 ViT 类似，AST 模型将音频频谱图分割成一系列部分重叠的 16×16 像素图像块。然后，
# 这一系列图像块被投影成一系列嵌入向量，并像往常一样作为输入提供给 Transformer 编码器。
# AST 是一个仅包含编码器的 Transformer 模型，因此其输出是一个隐藏状态序列，
# 每个 16×16 输入图像块对应一个隐藏状态。在此基础上，还有一个使用 sigmoid 激活函数的简单分类层，
# 用于将隐藏状态映射到分类概率。
# 任何变压器都可以是分类器
# 在前一节中，您已经了解到 CTC 是一种高效的自动语音识别技术，它仅使用编码器 Transformer 模型。
# 这类 CTC 模型本身就是分类器，能够根据分词器词汇表预测类别标签的概率。
# 我们可以通过更改标签并使用常规的交叉熵损失函数（而非 CTC 特有的损失函数）进行训练，将 CTC 模型转换为通用音频分类器。
#
# 例如，HF Transformers 有一个Wav2Vec2ForCTC模型，但也有Wav2Vec2ForSequenceClassification
# 其他Wav2Vec2ForAudioFrameClassification模型。这些模型架构之间的唯一区别在于分类层的大小和所使用的损失函数。
#
# 事实上，任何仅包含编码器的音频Transformer模型都可以通过在隐藏状态序列之上添加一个分类层，
# 转化为音频分类器。（分类器通常不需要Transformer解码器。）
#
# 为了预测整个序列的单一分类得分（Wav2Vec2ForSequenceClassification），
# 该模型取隐藏状态的均值，并将其输入到分类层。输出是一个单一的概率分布。
#
# 为了对每个音频帧进行单独分类（Wav2Vec2ForAudioFrameClassification），
# 分类器在隐藏状态序列上运行，因此分类器的输出也是一个序列。


"""
Writes synthetic sample rows into the manifest JSONL files.
Character/scene/style rows point at the placeholder PNGs generated by
04_DATASET/images/generate_placeholder_images.py (run first). Voice/video
rows use purely fabricated, non-existent file paths since this task does not
generate real audio/video files -- they exist only to exercise the loaders.
"""

from __future__ import annotations

import sys
from pathlib import Path

METADATA_DIR = Path(__file__).resolve().parent
DATASET_ROOT = METADATA_DIR.parent

sys.path.insert(0, str(DATASET_ROOT / "images"))
sys.path.insert(0, str(METADATA_DIR))

from generate_placeholder_images import generate_set  # noqa: E402

from schemas import (  # noqa: E402
    CharacterManifestEntry,
    SceneManifestEntry,
    StyleManifestEntry,
    VideoManifestEntry,
    VoiceManifestEntry,
)

CHARACTERS = ["char_lin_wei", "char_su_yan", "char_zhao_ming"]
ENVIRONMENTS = ["env_office_day", "env_alley_night"]
STYLES = ["style_cinematic_moody", "style_bright_commercial"]


def write_jsonl(path: Path, rows) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        for row in rows:
            f.write(row.model_dump_json() + "\n")


